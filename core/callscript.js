// Скрипт встречи «продающее интервью» под конкретного собственника.
// Каркас: рамка встречи (upfront contract, Sandler) → факты о компании → SPIN-вопросы
// (Situation/Problem/Implication/Need-payoff, Н. Рэкхем, исследование Huthwaite ~35 000 звонков)
// → решение его словами → возражения → закрытие вопросом с выбором (из твоего калькулятора).
import { DEFAULT_OFFERS, PROOFS, BRAND } from './catalog.js';
import { addressName, fmtMoney } from './util.js';
import { vacancyCost } from './economics.js';

export const OBJECTIONS = [
  { id: 'price', q: 'Дорого', a: 'Согласен, сумма заметная. Давайте сравним не с нулём, а с тем, что уже теряется: по вашим цифрам это {lost} в месяц. Решение окупается за {payback}. Что из этого расчёта кажется неверным?' },
  { id: 'think', q: 'Мне надо подумать', a: 'Конечно. Чтобы думать было о чём — что именно взвешиваете: результат, сроки или деньги? Если скажете, я сразу дам ответ, а не через неделю.' },
  { id: 'partner', q: 'Надо обсудить с партнёром', a: 'Правильно. Давайте я соберу для партнёра одну страницу: цифры, план, риски. И созвонимся втроём на 15 минут — ответы на его вопросы из первых уст.' },
  { id: 'time', q: 'Сейчас нет времени этим заниматься', a: 'Именно поэтому мы и берём это на себя: от вас — 2 часа в неделю на решения, всё остальное делаем мы. Сколько часов в неделю вы тратите на найм и продажи сейчас?' },
  { id: 'contractor', q: 'У нас уже есть подрядчик/РОП', a: 'Отлично. Какой показатель он гарантирует — выход человека или выполнение плана? У нас целевой ориентир по плану фиксируется в договоре. Могу дать второе мнение по воронке.' },
  { id: 'tried', q: 'Пробовали — не сработало', a: 'Что именно пробовали и на каком этапе сломалось? Чаще всего ломается не найм, а отсутствие воронки после выхода: обучение, аттестация, контроль. Это мы и закрываем.' },
  { id: 'guarantee', q: 'Какие гарантии?', a: 'Плановый показатель — в договоре, с обязательствами обеих сторон. Если менеджер не подошёл, не справился или пропал — замена в течение 30 дней без доплаты.' },
  { id: 'diy', q: 'Сделаем сами', a: 'Можно. Вопрос — во сколько это обойдётся по времени и ошибкам. У нас цена менеджера на плане — 13 928 ₽, потому что воронка уже отлажена на 29 360 откликах. Сколько у вас уходит на одного?' },
];

export const DISCOUNT_RULE = 'Скидка только в обмен на встречное условие: 100% предоплата, публичный отзыв, кейс или два контакта по рекомендации. Бонус — шаблоном, уроком или инструкцией из следующего тарифа, не услугой.';
export const CLOSE_LINE = '«Как удобнее — внести всю сумму сразу без наценки или стартовым платежом с рассрочкой?» — и дальше молчим, ждём ответа.';

export function buildCallScript({ lead = {}, me = {}, usdRate = 92, offers = DEFAULT_OFFERS } = {}) {
  const formal = lead.owner?.style?.formality !== 'ty';
  const name = addressName(lead.owner?.name || '', formal) || (formal ? 'коллега' : 'друг');
  const company = lead.company || 'компания';
  const facts = (lead.facts || []).slice(0, 5);
  const pains = (lead.hypotheses || []).map(h => h.pain);
  const cost = lead.inaction || vacancyCost({});
  const main = offers.find(o => o.id === lead.hypotheses?.[0]?.offerId) || offers.find(o => o.id === 'setup') || offers[0];
  const consult = offers.find(o => o.id === 'consult');
  const premium = offers.find(o => o.id === 'l3');
  const proof = PROOFS.find(p => p.id === 'bfl');
  const paybackMonths = cost.lostPerMonthRub ? Math.max(0.5, Math.round((main.priceRub / cost.lostPerMonthRub) * 10) / 10) : null;
  const money = (r) => fmtMoney(r, usdRate);

  const stages = [
    { id: 'frame', title: '1. Рамка встречи', min: 2, goal: 'Договориться о правилах: время, вопросы, честный итог.', say: [
      `${name}, спасибо, что нашли время. У нас 30–40 минут. Предлагаю так: я задам несколько вопросов, покажу, что уже вижу по ${company}, а в конце честно скажу — могу помочь или нет.`,
      'Если могу — расскажу как и сколько стоит. Если нет — дам рекомендации, и разойдёмся друзьями. Договорились?',
    ] },
    { id: 'wow', title: '2. Удивить фактами', min: 3, goal: 'Показать, что подготовился: 3 факта о компании.', say: [
      'Я подготовился и вот что увидел:',
      ...(facts.length ? facts.map(f => `— ${f.text}`) : ['— (добавьте 3 факта в карточку лида: сайт, вакансия, пост)']),
      'Что из этого неверно или уже изменилось?',
    ] },
    { id: 'situation', title: '3. Ситуация (S)', min: 5, goal: 'Минимум вопросов — главное мы уже знаем.', ask: [
      'Сколько заявок в месяц приходит в продажи и откуда?',
      'Сколько менеджеров сейчас и сколько из них стабильно делают план?',
      'Какой средний чек и цикл сделки?',
      'Кто сейчас управляет продажами — вы лично?',
    ] },
    { id: 'problem', title: '4. Проблема (P)', min: 8, goal: 'Найти этап, где теряются деньги. Гипотезы:', hints: pains, ask: [
      'На каком этапе — от заявки до оплаты — вы теряете больше всего?',
      `Почему вакансия ${lead.vacancy?.title ? '«' + lead.vacancy.title + '»' : 'руководителя'} до сих пор открыта? Кого уже смотрели?`,
      'Что сейчас мешает менеджерам выполнять план — люди, скрипты или контроль?',
    ] },
    { id: 'implication', title: '5. Последствия (I) — посчитать вместе', min: 8, goal: 'Перевести проблему в рубли его же цифрами.', ask: [
      'Если ничего не менять 3 месяца — сколько это в выручке?',
      'Сколько вашего личного времени в неделю уходит на найм и контроль продаж?',
      'Что будет, если новый руководитель не приживётся? Во сколько обошлась прошлая ошибка найма?',
    ], calc: `Ориентир по открытым данным: недобор ≈ ${money(cost.lostPerMonthRub)} в месяц; ошибка найма руководителя ≈ ${money(cost.badHireRiskRub)}. Уточните цифры у собственника и пересчитайте в калькуляторе.` },
    { id: 'payoff', title: '6. Выгода (N) — пусть скажет сам', min: 5, goal: 'Собственник формулирует ценность своими словами.', ask: [
      'Если бы через 60 дней отдел стабильно делал план — что бы это дало вам лично?',
      'Куда бы вы направили освободившееся время?',
      'Какой результат через 3 месяца вы бы назвали успехом?',
    ] },
    { id: 'offer', title: '7. Решение его словами', min: 7, goal: 'Предложить 2–3 варианта, начиная с основного. Цена в рублях и в долларах.', say: [
      `Смотрите, что я услышал: (повторить 2–3 его фразы о проблеме и выгоде).`,
      `Основной вариант — «${main.name}»: ${main.desc} Стоимость ${money(main.priceRub)}.${paybackMonths ? ` По открытым данным окупается примерно за ${String(paybackMonths).replace('.', ',')} мес. — уточним на ваших цифрах.` : ''}`,
      consult ? `Если хотите начать с малого — «${consult.name}» за ${money(consult.priceRub)}: план на 90 дней, который вы сможете внедрить и сами.` : '',
      premium ? `Если задача «под ключ» с командой — «${premium.name}», ${money(premium.priceRub)}.` : '',
      `Пример: ${proof.text}.`,
    ].filter(Boolean) },
    { id: 'objections', title: '8. Возражения', min: 5, goal: 'Слушать, уточнять, отвечать цифрами.', objections: OBJECTIONS.map(o => ({ ...o, a: o.a.replace('{lost}', money(cost.lostPerMonthRub)).replace('{payback}', paybackMonths ? paybackMonths + ' мес.' : 'несколько месяцев') })) },
    { id: 'close', title: '9. Закрытие', min: 2, goal: 'Вопрос с выбором и тишина.', say: [CLOSE_LINE, DISCOUNT_RULE] },
    { id: 'next', title: '10. Следующий шаг', min: 2, goal: 'Дата, счёт/договор, кто что делает.', say: [
      'Фиксирую: сегодня пришлю договор и счёт, старт — (дата). От вас — доступ к CRM и 1 час на установочную встречу.',
      'Если решение не сегодня — договариваемся о конкретной дате и времени следующего звонка прямо сейчас.',
    ] },
  ];

  return {
    title: `Скрипт встречи: ${company}${lead.owner?.name ? ' · ' + lead.owner.name : ''}`,
    durationMin: stages.reduce((a, s) => a + s.min, 0),
    tips: [
      'Говорите меньше половины времени: в открытых исследованиях Gong Labs у лучших продавцов доля речи около 43%.',
      'Задавайте 11–14 вопросов за встречу и не больше 3 подряд — это разговор, а не допрос.',
      'Цену называйте спокойно и один раз, затем молчите.',
      `Подпишитесь как ${me.name || BRAND.person}; после звонка загрузите запись — система разберёт её и обновит скрипт.`,
    ],
    stages,
  };
}
